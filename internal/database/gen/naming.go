// isSensitiveColumn reports columns that must not appear in JSON output.
func isSensitiveColumn(name string) bool {
	switch strings.ToLower(name) {
	case "password", "passwd", "secret", "token", "access_token", "refresh_token", "api_key":
		return true
	default:
		return false
	}
}

// commonInitialisms maps lowercase SQL name segments to Go initialisms.
var commonInitialisms = map[string]string{
	"id":    "ID",
	"url":   "URL",
	"uri":   "URI",
	"api":   "API",
	"ip":    "IP",
	"uid":   "UID",
	"uuid":  "UUID",
	"http":  "HTTP",
	"https": "HTTPS",
	"json":  "JSON",
	"xml":   "XML",
	"sql":   "SQL",
	"pk":    "PK",
	"fk":    "FK",
	"pv":    "PV",
	"uv":    "UV",
}

// ToAlias generates a short alias from a snake_case table name. For tables
// with a single segment, the first two letters are used (e.g. actors -> ac,
// admins -> ad) to avoid collisions between tables that share the first letter.
// Multi-segment names use the first letter of each segment (e.g. site_stats_daily -> ssd).
func ToAlias(tableName string) string {
	parts := strings.Split(tableName, "_")
	if len(parts) == 0 {
		return "t"
	}
	if len(parts) == 1 {
		if len(tableName) >= 2 {
			return tableName[:2]
		}
		return tableName
	}
	var alias strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		alias.WriteRune(rune(p[0]))
	}
	if alias.Len() == 0 {
		return "t"
	}
	return alias.String()
}

// ToCamelCase converts snake_case to CamelCase (with common initialisms).
func ToCamelCase(s string) string {
	parts := strings.Split(s, "_")
	for i, part := range parts {
		lower := strings.ToLower(part)
		if repl, ok := commonInitialisms[lower]; ok {
			parts[i] = repl
			continue
		}
		parts[i] = titleCaser.String(part)
	}
	return strings.Join(parts, "")
}

// ToSnakeCase converts CamelCase to snake_case.
func ToSnakeCase(s string) string {
	var result []rune
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			prev := rune(s[i-1])
			if prev >= 'a' && prev <= 'z' {
				result = append(result, '_')
			} else if i+1 < len(s) && rune(s[i+1]) >= 'a' && rune(s[i+1]) <= 'z' && prev >= 'A' && prev <= 'Z' {
				result = append(result, '_')
			}
		}
		result = append(result, r)
	}
	return strings.ToLower(string(result))
}

// MapSQLTypeToGo maps a SQL type name to a Go type.
func MapSQLTypeToGo(sqlType string, nullable, unsigned bool) string {
	typeMap := map[string]string{
		"tinyint":   "int8",
		"smallint":  "int16",
		"int":       "int32",
		"integer":   "int32",
		"bigint":    "int64",
		"float":     "float32",
		"double":    "float64",
		"decimal":   "float64",
		"numeric":   "float64",
		"char":      "string",
		"varchar":   "string",
		"text":      "string",
		"date":      "time.Time",
		"datetime":  "time.Time",
		"timestamp": "time.Time",
		"boolean":   "bool",
		"json":      "string",
		"real":      "float64",
		"blob":      "[]byte",
	}

	goType, ok := typeMap[strings.ToLower(sqlType)]
	if !ok {
		goType = "string"
	}

	if unsigned {
		switch goType {
		case "int8":
			goType = "uint8"
		case "int16":
			goType = "uint16"
		case "int32":
			goType = "uint32"
		case "int64":
			goType = "uint64"
		}
	}

	if nullable {
		goType = "*" + goType
	}

	return goType
}

// GenerateModelCode renders Go struct source for a database table.
func GenerateModelCode(opts GenerateOptions, modelName, tableName string, columns []Column, relations []Relation) string {
	var sb strings.Builder

	sb.WriteString("// Code generated by orange-tv gen model. DO NOT EDIT.\n\n")

	sb.WriteString(fmt.Sprintf("package %s\n\n", opts.PackageName))

	hasTime := false
	for _, col := range columns {
		goType := MapSQLTypeToGo(col.Type, col.Nullable, col.Unsigned)
		if goType == "time.Time" || goType == "*time.Time" {
			hasTime = true
			break
		}
	}

	// Detect timestamp columns for BeforeAppendModelHook generation.
	var hasCreatedAt, hasUpdatedAt bool
	var createdAtNullable, updatedAtNullable bool
	for _, col := range columns {
		switch col.Name {
		case "created_at":
			hasCreatedAt = true
			createdAtNullable = col.Nullable
		case "updated_at":
			hasUpdatedAt = true
			updatedAtNullable = col.Nullable
		}
	}
	hasHook := hasCreatedAt || hasUpdatedAt

	sb.WriteString("import (\n")
	if hasHook {
		sb.WriteString("\t\"context\"\n\n")
	}
	if hasTime || hasHook {
		sb.WriteString("\t\"time\"\n\n")
	}
	sb.WriteString("\t\"github.com/uptrace/bun\"\n")
	sb.WriteString(")\n\n")

	sb.WriteString(fmt.Sprintf("// %s represents the %s table.\n", modelName, tableName))
	sb.WriteString(fmt.Sprintf("type %s struct {\n", modelName))

	alias := ToAlias(tableName)
	sb.WriteString(fmt.Sprintf("\tbun.BaseModel `bun:\"table:%s,alias:%s\"`\n\n", tableName, alias))

	for _, col := range columns {
		if col.Comment != "" {
			sb.WriteString(fmt.Sprintf("\t// %s\n", col.Comment))
		}

		goType := MapSQLTypeToGo(col.Type, col.Nullable, col.Unsigned)
		fieldName := ToCamelCase(col.Name)

		for _, relation := range relations {
			if relation.SourceTable == tableName && relation.SourceColumn == col.Name {
				refModel := ToCamelCase(relation.TargetTable)
				refField := ToCamelCase(relation.TargetColumn)
				sb.WriteString(fmt.Sprintf("\t// Relation: %s -> %s(%s)\n", col.Name, refModel, refField))
				break
			}
		}

		bunTag := col.Name
		if col.PrimaryKey {
			bunTag += ",pk"
			if col.AutoIncrement {
				bunTag += ",autoincrement"
			}
		}
		if !col.Nullable && !col.PrimaryKey {
			bunTag += ",notnull"
		}
		if col.Unique {
			if col.UniqueGroup != "" {
				bunTag += ",unique:" + col.UniqueGroup
			} else {
				bunTag += ",unique"
			}
		}
		tags := []string{fmt.Sprintf(`bun:"%s"`, bunTag)}
		if opts.JSONTags {
			// Prefer DB column names (already snake_case); hide sensitive fields.
			jsonName := col.Name
			if isSensitiveColumn(col.Name) {
				jsonName = "-"
			}
			tags = append(tags, fmt.Sprintf(`json:"%s"`, jsonName))
		}
		if opts.ValidatorTags && !col.Nullable && !isSensitiveColumn(col.Name) {
			tags = append(tags, `binding:"required"`)
		}

		sb.WriteString(fmt.Sprintf("\t%s %s `%s`\n", fieldName, goType, strings.Join(tags, " ")))
	}

	for _, relation := range relations {
		field, reverseField := relationFieldNames(relation)
		if relation.SourceTable == tableName {
			sb.WriteString(fmt.Sprintf("\t%s *%s `bun:\"rel:belongs-to,join:%s=%s\" json:\"-\"`\n", field, ToCamelCase(relation.TargetTable), relation.SourceColumn, relation.TargetColumn))
		}
		if relation.TargetTable == tableName {
			sb.WriteString(fmt.Sprintf("\t%s []*%s `bun:\"rel:has-many,join:%s=%s\" json:\"-\"`\n", reverseField, ToCamelCase(relation.SourceTable), relation.TargetColumn, relation.SourceColumn))
		}
	}

	sb.WriteString("}\n")

	if hasHook {
		sb.WriteString("\n")
		sb.WriteString(fmt.Sprintf("var _ bun.BeforeAppendModelHook = (*%s)(nil)\n\n", modelName))
		sb.WriteString(fmt.Sprintf("func (m *%s) BeforeAppendModel(ctx context.Context, query bun.Query) error {\n", modelName))
		sb.WriteString("\tnow := time.Now()\n")
		sb.WriteString("\tswitch query.(type) {\n")
		if hasCreatedAt {
			sb.WriteString("\tcase *bun.InsertQuery:\n")
			if createdAtNullable {
				sb.WriteString("\t\tm.CreatedAt = &now\n")
			} else {
				sb.WriteString("\t\tm.CreatedAt = now\n")
			}
			if hasUpdatedAt {
				if updatedAtNullable {
					sb.WriteString("\t\tm.UpdatedAt = &now\n")
				} else {
					sb.WriteString("\t\tm.UpdatedAt = now\n")
				}
			}
		}
		if hasUpdatedAt {
			sb.WriteString("\tcase *bun.UpdateQuery:\n")
			if updatedAtNullable {
				sb.WriteString("\t\tm.UpdatedAt = &now\n")
			} else {
				sb.WriteString("\t\tm.UpdatedAt = now\n")
			}
		}
		sb.WriteString("\t}\n")
		sb.WriteString("\treturn nil\n")
		sb.WriteString("}\n")
	}

	return sb.String()
}
